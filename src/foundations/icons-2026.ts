/** Unique icons (first occurrence wins) + bookkeeping computed from the raw rows. */
export const icons = (() => {
  const seen = new Map<string, { name: string; x: number; y: number }>();
  const dupes: string[] = [];
  for (const [name, x, y] of iconRows) {
    if (seen.has(name)) dupes.push(name);
    else seen.set(name, { name, x, y });
  }
  return { list: [...seen.values()].sort((a, b) => a.name.localeCompare(b.name)), dupes };
})();

